import sqlite3, os, sys
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ['TEMP'], 'finance_device3.db')
con = sqlite3.connect(path)
con.text_factory = lambda b: b.decode('utf-8', 'replace')
print('meta', con.execute("select key, value from app_meta").fetchall())
print('processed', con.execute('select processed, count(*) from sms_messages group by processed').fetchall())
print('classes', con.execute('select class, count(*) from sms_messages group by class').fetchall())
print('txns', con.execute('select count(*) from transactions').fetchone()[0])
print('cards', con.execute('select count(*) from cards').fetchone()[0])
print('bills', con.execute('select count(*) from card_bills').fetchone()[0])
